"""Rebuild the installation SQL exclusively from the canonical migration chain."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
HEADER = '-- GENERATED by scripts/database.py. Edit supabase/migrations/*.sql only.\n'

def combined():
    return HEADER + '\n'.join('-- Migration: '+p.name+'\n'+p.read_text(encoding='utf-8').strip()+'\n' for p in sorted((ROOT/'supabase/migrations').glob('*.sql')))

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    target=ROOT/'supabase.sql';expected=combined()
    if args.write: target.write_text(expected,encoding='utf-8',newline='\n')
    else:
        if target.read_text(encoding='utf-8')!=expected:raise SystemExit('supabase.sql is stale: run python scripts/database.py --write')
        print('Canonical database migrations and installation SQL match.')
